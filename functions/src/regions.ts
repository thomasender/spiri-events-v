/**
 * Region helpers for Cloud Functions. functions/ cannot import from src/, so
 * resolveRegionId is a small copy of src/utils/regions.js. KEEP BOTH IN SYNC:
 * tests/components/regions.spec.ts and tests/lib/functionsRegions.spec.ts run
 * the same cases against the two copies.
 */

import { LEGACY_BEZIRKE, REGION_DATA } from './regionData';

/** Register Bezirke plus the legacy pseudo-Bezirke of old events (Vorarlberg's "Grenznahe"). */
const withLegacyBezirke = (slug: string, bezirke: readonly string[]): string[] => [
  ...bezirke,
  ...(LEGACY_BEZIRKE[slug] ?? []),
];

export const DEFAULT_REGION_ID = 'vorarlberg';

/**
 * Region ids: the regions of the three country CSVs in scripts/data/regions/ (Austria,
 * Switzerland, Liechtenstein), same order as REGION_SLUGS in src/utils/regions.js and
 * regionIds() in firestore.rules (guarded by tests/lib/functionsRegions.spec.ts).
 * Data generated by scripts/build-region-data.mjs.
 */
export const STATIC_REGION_IDS: readonly string[] = REGION_DATA.map((r) => r.slug);

/** All region ids (the generated register is the only source). */
export const REGION_IDS: readonly string[] = STATIC_REGION_IDS;

/** Stored ids read as another region (copy of src/utils/regions.js; empty since the CSV register). */
export const LEGACY_REGION_ALIASES: Readonly<Record<string, string>> = {};

/**
 * Districts (Bezirke / Landkreise) known without Firestore, in the order of
 * DIRECTORY_REGIONS in src/utils/directory.js (all districts of all regions,
 * Vorarlberg first, then "Online"). A directory profile may only name these
 * Synced copy, guarded by
 * tests/lib/functionsRegions.spec.ts.
 */
export const DIRECTORY_REGIONS: readonly string[] = [
  ...new Set(
    [
      ...REGION_DATA.filter((r) => r.slug === DEFAULT_REGION_ID),
      ...REGION_DATA.filter((r) => r.slug !== DEFAULT_REGION_ID),
    ].flatMap((r) => withLegacyBezirke(r.slug, r.bezirke))
  ),
  'Online',
];

export function isRegionId(value: unknown): value is string {
  return typeof value === 'string' && REGION_IDS.includes(value);
}

/** Display name of a region, else null. */
export function regionNameOf(id: string): string | null {
  return REGION_DATA.find((r) => r.slug === id)?.name ?? null;
}

/**
 * Combined views ("Ganz Österreich", "Ganz Schweiz", "Alle Tribes"): UI views over the active regions of one country (`country`) or of
 * all countries (`country: null`), never stored on an event. Synced copy of
 * COMBINED_VIEWS in src/utils/regions.js (guarded by tests/lib/functionsRegions.spec.ts);
 * the feed accepts their slugs as `region=`.
 */
export interface CombinedView {
  slug: string;
  label: string;
  country: string | null;
}
export const COMBINED_VIEWS: readonly CombinedView[] = [
  { slug: 'oesterreich', label: 'Österreich', country: 'AT' },
  { slug: 'schweiz', label: 'Schweiz', country: 'CH' },
  { slug: 'alle-tribes', label: 'Alle Tribes', country: null },
];

export function getCombinedView(value: unknown): CombinedView | null {
  return COMBINED_VIEWS.find((v) => v.slug === value) ?? null;
}

/** Country of each region (from the generated register data; default AT). */
export const STATIC_COUNTRIES: Record<string, string> = Object.fromEntries(
  REGION_DATA.map((r) => [r.slug, r.country])
);
export const DEFAULT_COUNTRY = 'AT';

/** Country of a region id (default AT). */
export function countryOfRegion(id: string): string {
  return STATIC_COUNTRIES[id] ?? DEFAULT_COUNTRY;
}

/**
 * Regions that always have an Instagram account: Vorarlberg, via the legacy
 * global secrets IG_ACCESS_TOKEN / IG_USER_ID. Other regions get an account by
 * Thomas storing credentials in instagram_private/region_{id}
 * (scripts/instagram-set-region-account.mjs, docs/instagram-regions.md); the
 * feed trigger and the backfill then pass that region id as `regionIds` below.
 * The weekly carousel and the stories are still Vorarlberg-only and call
 * isInstagramRegion without `regionIds`, so they keep this list.
 */
export const INSTAGRAM_REGION_IDS: readonly string[] = ['vorarlberg'];

/** Read fallback for documents written before regions existed. */
export function resolveRegionId(doc: unknown): string {
  const regionId = doc && typeof doc === 'object' ? (doc as { regionId?: unknown }).regionId : null;
  return typeof regionId === 'string' && regionId
    ? (LEGACY_REGION_ALIASES[regionId] ?? regionId)
    : DEFAULT_REGION_ID;
}

/** Online events count by their moderation region (`regionId`), like all others. */
export function isInstagramRegion(
  event: unknown,
  regionIds: readonly string[] = INSTAGRAM_REGION_IDS
): boolean {
  return regionIds.includes(resolveRegionId(event));
}

/** Online events are visible in every region (copy of eventVisibleInRegion). */
export function eventVisibleInRegion(event: unknown, regionId: string): boolean {
  const online =
    event && typeof event === 'object' ? (event as { isOnline?: unknown }).isOnline : null;
  if (online) return true;
  return resolveRegionId(event) === regionId;
}

/**
 * Copy of filterEventsForRegion in src/utils/regions.js: events of active
 * regions only; with `regionId` additionally that region's events plus online
 * events. No `regionId` or `isNational`: every event of an active region.
 */
export function filterEventsForRegion<T>(
  events: T[],
  opts: { regionId?: string | null; isNational?: boolean; activeRegionIds?: readonly string[] } = {}
): T[] {
  const { regionId = null, isNational = false, activeRegionIds = [DEFAULT_REGION_ID] } = opts;
  if (!Array.isArray(events)) return [];
  const active = new Set(activeRegionIds);
  const all = isNational || !regionId;
  return events.filter(
    (event) =>
      active.has(resolveRegionId(event)) && (all || eventVisibleInRegion(event, regionId as string))
  );
}

export interface FeedRegion {
  id: string;
  name: string;
  country: string;
  active: boolean;
  bezirke: string[];
  timezone: string;
}

export const DEFAULT_REGION_TIMEZONE = 'Europe/Vienna';

const STATIC_NAMES: Record<string, string> = Object.fromEntries(
  REGION_DATA.map((r) => [r.slug, r.name])
);

/** Bezirke known without Firestore (copy of the register data in src/utils/regions.js). */
export const STATIC_REGION_BEZIRKE: Record<string, readonly string[]> = Object.fromEntries(
  REGION_DATA.map((r) => [r.slug, withLegacyBezirke(r.slug, r.bezirke)])
);

const STATIC_TIMEZONES: Record<string, string> = Object.fromEntries(
  REGION_DATA.map((r) => [r.slug, r.timezone])
);
const TIMEZONE_PATTERN = /^[A-Za-z]+(?:\/[A-Za-z0-9_+-]+){1,2}$/;

/** Static register (only Vorarlberg active), as in STATIC_REGIONS of src/utils/regions.js. */
export const STATIC_FEED_REGIONS: FeedRegion[] = STATIC_REGION_IDS.map((id) => ({
  id,
  name: STATIC_NAMES[id],
  country: STATIC_COUNTRIES[id] ?? DEFAULT_COUNTRY,
  active: id === DEFAULT_REGION_ID,
  bezirke: [...(STATIC_REGION_BEZIRKE[id] ?? [])],
  timezone: STATIC_TIMEZONES[id] ?? DEFAULT_REGION_TIMEZONE,
}));

/** Region ids a combined view covers: its country's regions (`activeOnly`: the active ones only). */
export function combinedViewRegionIds(
  view: CombinedView,
  regions: readonly FeedRegion[] = STATIC_FEED_REGIONS,
  activeOnly = true
): string[] {
  return regions
    .filter((r) => (!activeOnly || r.active) && (!view.country || r.country === view.country))
    .map((r) => r.id);
}

/**
 * Bezirke accepted by `bezirk=` per combined view slug: the union over all
 * regions of the view's scope (active or not).
 */
export function combinedViewBezirke(
  regions: readonly FeedRegion[] = STATIC_FEED_REGIONS
): Record<string, string[]> {
  return Object.fromEntries(
    COMBINED_VIEWS.map((v) => {
      const ids = new Set(combinedViewRegionIds(v, regions, false));
      return [v.slug, [...new Set(regions.filter((r) => ids.has(r.id)).flatMap((r) => r.bezirke))]];
    })
  );
}

/**
 * Lays `regions/{id}` docs ({ id, ...data }) over the static register (copy of mergeRegions).
 * Districts and names come only from the register; the docs switch regions on and off
 * and may set the timezone.
 */
export function mergeFeedRegions(docs: unknown[]): FeedRegion[] {
  const byId = new Map<string, Record<string, unknown>>();
  for (const d of docs) {
    const doc = d as Record<string, unknown> | null;
    if (doc && isRegionId(doc.id)) byId.set(doc.id as string, doc);
  }
  return STATIC_FEED_REGIONS.map((r) => {
    const d = byId.get(r.id);
    if (!d) return r;
    return {
      ...r,
      ...(typeof d.active === 'boolean' ? { active: d.active } : {}),
      ...(typeof d.timezone === 'string' && TIMEZONE_PATTERN.test(d.timezone)
        ? { timezone: d.timezone }
        : {}),
    };
  });
}
