#!/usr/bin/env node
// Builds the silent map of Germany, Austria and Switzerland for the region
// chooser (src/components/RegionMap.jsx) -> src/data/regionMap.js.
//
// Source: Natural Earth "Admin 1 - States, Provinces" 1:10m (public domain,
// https://www.naturalearthdata.com/). scripts/data/dach-regions.geojson is that
// data reduced to the 51 regions and simplified, produced with
//   npx mapshaper ne_10m_admin_1_states_provinces.geojson \
//     -filter 'iso_a2=="AT"||iso_a2=="DE"||iso_a2=="CH"' -filter-fields iso_3166_2 \
//     -simplify 14% keep-shapes -o scripts/data/dach-regions.geojson precision=0.001
// Regions are matched by ISO 3166-2 code (not by name), then projected (Mercator)
// into one SVG viewBox. Run:  node scripts/build-region-map.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { REGION_SLUGS } from '../src/utils/regions.js';

const root = new URL('..', import.meta.url).pathname;

const ISO_TO_SLUG = {
  'AT-1': 'burgenland',
  'AT-2': 'kaernten',
  'AT-3': 'niederoesterreich',
  'AT-4': 'oberoesterreich',
  'AT-5': 'salzburg',
  'AT-6': 'steiermark',
  'AT-7': 'tirol',
  'AT-8': 'vorarlberg',
  'AT-9': 'wien',
  'DE-BW': 'baden-wuerttemberg',
  'DE-BY': 'bayern',
  'DE-BE': 'berlin',
  'DE-BB': 'brandenburg',
  'DE-HB': 'bremen',
  'DE-HH': 'hamburg',
  'DE-HE': 'hessen',
  'DE-MV': 'mecklenburg-vorpommern',
  'DE-NI': 'niedersachsen',
  'DE-NW': 'nordrhein-westfalen',
  'DE-RP': 'rheinland-pfalz',
  'DE-SL': 'saarland',
  'DE-SN': 'sachsen',
  'DE-ST': 'sachsen-anhalt',
  'DE-SH': 'schleswig-holstein',
  'DE-TH': 'thueringen',
  'CH-ZH': 'zuerich',
  'CH-BE': 'bern',
  'CH-LU': 'luzern',
  'CH-UR': 'uri',
  'CH-SZ': 'schwyz',
  'CH-OW': 'obwalden',
  'CH-NW': 'nidwalden',
  'CH-GL': 'glarus',
  'CH-ZG': 'zug',
  'CH-FR': 'freiburg',
  'CH-SO': 'solothurn',
  'CH-BS': 'basel-stadt',
  'CH-BL': 'basel-landschaft',
  'CH-SH': 'schaffhausen',
  'CH-AR': 'appenzell-ausserrhoden',
  'CH-AI': 'appenzell-innerrhoden',
  'CH-SG': 'st-gallen',
  'CH-GR': 'graubuenden',
  'CH-AG': 'aargau',
  'CH-TG': 'thurgau',
  'CH-TI': 'tessin',
  'CH-VD': 'waadt',
  'CH-VS': 'wallis',
  'CH-NE': 'neuenburg',
  'CH-GE': 'genf',
  'CH-JU': 'jura',
};

const WIDTH = 1000;
const rad = (d) => (d * Math.PI) / 180;
const mercator = ([lon, lat]) => [rad(lon), Math.log(Math.tan(Math.PI / 4 + rad(lat) / 2))];

const geo = JSON.parse(readFileSync(root + 'scripts/data/dach-regions.geojson', 'utf8'));
const polysOf = (g) => (g.type === 'Polygon' ? [g.coordinates] : g.coordinates);

// Projected rings per region, and the overall bounds.
const regions = new Map();
let minX = Infinity;
let maxX = -Infinity;
let minY = Infinity;
let maxY = -Infinity;
for (const f of geo.features) {
  const slug = ISO_TO_SLUG[f.properties.iso_3166_2];
  if (!slug) throw new Error(`Unmapped region ${f.properties.iso_3166_2}`);
  const polys = polysOf(f.geometry).map((rings) => rings.map((ring) => ring.map(mercator)));
  for (const rings of polys)
    for (const ring of rings)
      for (const [x, y] of ring) {
        minX = Math.min(minX, x);
        maxX = Math.max(maxX, x);
        minY = Math.min(minY, y);
        maxY = Math.max(maxY, y);
      }
  regions.set(slug, polys);
}
const missing = REGION_SLUGS.filter((s) => !regions.has(s));
if (missing.length) throw new Error(`Regions without map shape: ${missing.join(', ')}`);

const pad = 8;
const scale = (WIDTH - 2 * pad) / (maxX - minX);
const height = Math.round((maxY - minY) * scale + 2 * pad);
// SVG y grows downwards.
const px = ([x, y]) => [(x - minX) * scale + pad, (maxY - y) * scale + pad];
const r1 = (n) => Math.round(n * 10) / 10;

// Signed area and centroid of one ring (shoelace), in SVG units.
function ringStats(ring) {
  let a = 0;
  let cx = 0;
  let cy = 0;
  for (let i = 0; i < ring.length - 1; i++) {
    const [x0, y0] = ring[i];
    const [x1, y1] = ring[i + 1];
    const cross = x0 * y1 - x1 * y0;
    a += cross;
    cx += (x0 + x1) * cross;
    cy += (y0 + y1) * cross;
  }
  a /= 2;
  return { area: Math.abs(a), cx: cx / (6 * a), cy: cy / (6 * a) };
}

const out = REGION_SLUGS.map((id) => {
  const polys = regions.get(id).map((rings) => rings.map((ring) => ring.map(px)));
  const d = polys
    .map((rings) =>
      rings
        .map((ring) => ring.map((p, i) => `${i ? 'L' : 'M'}${r1(p[0])} ${r1(p[1])}`).join('') + 'Z')
        .join('')
    )
    .join('');
  // Label anchor: centroid of the biggest outer ring; area = all outer rings.
  const outer = polys.map((rings) => ringStats(rings[0]));
  const biggest = outer.reduce((a, b) => (b.area > a.area ? b : a));
  const area = outer.reduce((n, o) => n + o.area, 0);
  return { id, d, cx: r1(biggest.cx), cy: r1(biggest.cy), area: Math.round(area) };
});

const body = `// GENERATED by scripts/build-region-map.mjs from Natural Earth Admin 1 (public domain). Do not edit by hand.
export const REGION_MAP = ${JSON.stringify({ viewBox: `0 0 ${WIDTH} ${height}`, regions: out })};
`;
writeFileSync(root + 'src/data/regionMap.js', body);
console.log(
  `${out.length} regions, viewBox 0 0 ${WIDTH} ${height}, ${Math.round(body.length / 1024)} KB`
);
console.log(
  'smallest:',
  [...out]
    .sort((a, b) => a.area - b.area)
    .slice(0, 8)
    .map((r) => `${r.id}:${r.area}`)
    .join(' ')
);
