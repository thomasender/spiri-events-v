export default function EmojiPicker({ onPick, onClose }) {
  const [groupId, setGroupId] = useState(EMOJI_GROUPS[0].id);
  const group = EMOJI_GROUPS.find((g) => g.id === groupId) ?? EMOJI_GROUPS[0];

  return (
    <div
      className="emoji-picker"
      role="dialog"
      aria-label="Emoji auswählen"
      data-testid="emoji-picker"
      onKeyDown={(e) => {
        if (e.key === 'Escape') {
          e.stopPropagation();
          onClose?.();
        }
      }}
    >
      <div className="emoji-picker-tabs" role="tablist">
        {EMOJI_GROUPS.map((g) => (
          <button
            key={g.id}
            type="button"
            role="tab"
            aria-selected={g.id === group.id}
            aria-label={g.label}
            title={g.label}
            className={`emoji-picker-tab${g.id === group.id ? ' emoji-picker-tab--active' : ''}`}
            onClick={() => setGroupId(g.id)}
          >
            {g.icon}
          </button>
        ))}
      </div>
      <div className="emoji-picker-grid" role="tabpanel">
        {group.emojis.map((emoji) => (
          <button
            key={emoji}
            type="button"
            className="emoji-picker-item"
            aria-label={emoji}
            onClick={() => onPick(emoji)}
          >
            {emoji}
          </button>
        ))}
      </div>
    </div>
  );
}
